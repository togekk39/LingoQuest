type Objective = keyof typeof cartagenaLessonIds;
type Speaker = 'Sam' | 'Luz' | 'Mar' | 'Alba';
type Stage = Extract<TravelStep, { type: 'teach' }>;

const pair = (en: string, es: string): Translation => ({ en, es });

function word(
  term: string,
  meaning: string,
  reference: PrerequisiteReference,
  example: Translation,
): TravelVocabulary {
  return { term, meaning, kind: 'Inglés', explanation: meaning, teaches: [reference], example };
}

function teach(
  objective: Objective,
  name: string,
  speaker: Speaker,
  title: string,
  text: string,
  examples: Translation[],
  references: PrerequisiteReference[],
  vocabularyTerms: string[] = [],
): Stage {
  return {
    id: `cartagena-${objective}-${name}-teach`,
    type: 'teach',
    speaker,
    title,
    text,
    vocabularyTerms,
    examples,
    instruction: {
      lessonId: cartagenaLessonIds[objective],
      stage: vocabularyTerms.length ? 'both' : 'grammar',
      references,
    },
  };
}

