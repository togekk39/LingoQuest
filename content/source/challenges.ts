const grammarRush: PrivateExercise[] = grammarSeeds.flatMap((seeds, tier) =>
  seeds.map(([sentence, answer, distractor1, distractor2, feedbackEs], index) => {
    const entries = [answer, distractor1, distractor2];
    const shift = (index + tier) % entries.length;
    const choices = [...entries.slice(shift), ...entries.slice(0, shift)];
    return {
      id: `gr_l${String(tier + 1).padStart(2, '0')}_${String(index + 1).padStart(2, '0')}`,
      type: 'single_choice' as const,
      promptEs: 'Elige la opción que completa la oración.',
      sentence,
      options: choices.map((text, i) => ({ id: String.fromCharCode(97 + i), text })),
      correctOptionId: String.fromCharCode(97 + choices.indexOf(answer)),
      acceptedAnswers: [answer],
      skillId:
        tier < 3
          ? 'grammar.third_person_s'
          : tier < 5
            ? 'grammar.questions'
            : 'grammar.present_simple',
      feedbackEs,
      difficulty: tier + 1,
    };
  }),
);

type PassageQuestion = readonly [string, string, string, string, string];
function passageItems(
  prefix: string,
  passage: string,
  questions: readonly PassageQuestion[],
  difficulty: number,
  type: 'cloze' | 'single_choice',
): PrivateExercise[] {
  return questions.map(([sentence, answer, wrong1, wrong2, feedbackEs], i) => {
    const values = [answer, wrong1, wrong2];
    const shift = i % 3;
    const choices = [...values.slice(shift), ...values.slice(0, shift)];
    return {
      id: `${prefix}_${i + 1}`,
      type,
      promptEs:
        type === 'cloze'
          ? 'Lee el texto y completa el espacio indicado.'
          : 'Lee el texto y responde según la información disponible.',
      sentence,
      passage,
      options: choices.map((text, j) => ({ id: String.fromCharCode(97 + j), text })),
      correctOptionId: String.fromCharCode(97 + choices.indexOf(answer)),
      acceptedAnswers: [answer],
      skillId: 'grammar.present_simple',
      feedbackEs,
      difficulty,
    };
  });
}

