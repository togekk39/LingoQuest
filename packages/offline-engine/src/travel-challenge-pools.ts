import type { CourseExercise } from './index';

function fill(
  id: string,
  sentence: string,
  promptEs: string,
  acceptedAnswers: string[],
  feedbackEs: string,
  skillId: string,
): CourseExercise {
  return {
    id: `home_challenge_${id}`,
    type: 'short_text',
    sentence,
    promptEs,
    acceptedAnswers,
    feedbackEs,
    skillId,
    difficulty: 1,
  };
}
function read(
  id: string,
  passage: string,
  promptEs: string,
  answer: string,
  other: string,
  feedbackEs: string,
  skillId: string,
): CourseExercise {
  return {
    id: `home_challenge_${id}`,
    type: 'meaning',
    passage,
    promptEs,
    optionsLanguage: 'es',
    options: [
      { id: 'other', text: other },
      { id: 'right', text: answer },
    ],
    correctOptionId: 'right',
    acceptedAnswers: [answer],
    feedbackEs,
    skillId,
    difficulty: 1,
  };
}

